package com.nak.demo.Controller;

import com.nak.demo.Model.BaseResponseModel;
import com.nak.demo.Model.BaseResponseModelWithData;
import com.nak.demo.dto.user.ChangePasswordDto;
import com.nak.demo.dto.user.UpdateUserDto;
import com.nak.demo.exception.model.ResourceNotFoundException;
import com.nak.demo.dto.user.UserDto;
import com.nak.demo.Service.UserService;
import jakarta.validation.Valid;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/api/v1/users")
public class UserController {
    @Autowired
    private UserService userService;

    @GetMapping()
    public ResponseEntity<BaseResponseModelWithData> listUsers() {

        return userService.listUser();
    }
    @GetMapping("/{user_id}")
    public ResponseEntity<BaseResponseModelWithData> getUser(@PathVariable ("user_id") Long userId){
        return userService.getUser(userId);
    }
    @PostMapping
    public ResponseEntity<BaseResponseModel> createUser(@Valid  @RequestBody UserDto payload) {
        return userService.createUser( payload);
    }

    @PutMapping("/{user_id}")
    public ResponseEntity<BaseResponseModel> updateUser(@PathVariable("user_id") Long userId,
                                                       @Valid @RequestBody UpdateUserDto payload) {
        return userService.updateUser( payload,userId);
    }

    @DeleteMapping("/{user_id}")
    public  ResponseEntity<BaseResponseModel> deleteUser(@PathVariable("user_id") Long userId){
      return userService.deleteUser(userId);
    }
    @PatchMapping("/{user_id}/change-password")
    public ResponseEntity<BaseResponseModel> changePassword(@PathVariable ("user_id") Long userId,@RequestBody ChangePasswordDto dto){
            return userService.changePassword(dto,userId);
    }
    @GetMapping("/search")
    public ResponseEntity<BaseResponseModelWithData> findUser(
      @RequestParam( value = "name", required = false) String name
    ){
        return userService.findUser(name);
    }














































































































































































































































































































































































































































































































































}